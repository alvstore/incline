import { useState } from 'react';
import { Sheet, SheetContent, SheetDescription, SheetHeader, SheetTitle, SheetFooter } from '@/components/ui/sheet';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { PhoneInput } from '@/components/ui/PhoneInput';
import { Label } from '@/components/ui/label';
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';
import { supabase } from '@/integrations/supabase/client';
import { useQueryClient, useQuery } from '@tanstack/react-query';
import { toast } from 'sonner';
import { useBranches } from '@/hooks/useBranches';
import { UserPlus, Link, Info } from 'lucide-react';
import { StaffAvatarUpload } from '@/components/common/StaffAvatarUpload';
import { DEPARTMENTS, POSITIONS, SALARY_TYPES } from '@/constants/employeeConstants';
import { DefaultPasswordCard, DEFAULT_TEMP_PASSWORD } from '@/components/auth/TempPasswordField';

interface AddEmployeeDrawerProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
}

export function AddEmployeeDrawer({ open, onOpenChange }: AddEmployeeDrawerProps) {
  const queryClient = useQueryClient();
  const { data: branches = [] } = useBranches();
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [activeTab, setActiveTab] = useState<'new' | 'link'>('new');
  const [avatarUrl, setAvatarUrl] = useState('');

  // Form data for linking existing user
  const [linkFormData, setLinkFormData] = useState({
    user_id: '',
    branch_id: '',
    department: '',
    position: '',
    hire_date: new Date().toISOString().split('T')[0],
    salary: '',
    salary_type: 'monthly',
    bank_name: '',
    bank_account: '',
    tax_id: '',
    role: 'staff' as 'staff' | 'manager',
  });

  // Form data for creating new user
  const [newUserFormData, setNewUserFormData] = useState({
    email: '',
    full_name: '',
    phone: '',
    branch_id: '',
    department: '',
    position: '',
    hire_date: new Date().toISOString().split('T')[0],
    salary: '',
    salary_type: 'monthly',
    bank_name: '',
    bank_account: '',
    tax_id: '',
    role: 'staff' as 'staff' | 'manager',
  });

  // Fetch available users who are NOT already employees AND NOT members
  const { data: availableUsers = [] } = useQuery({
    queryKey: ['available-users-for-employees'],
    queryFn: async () => {
      const { data: existingEmployees } = await supabase
        .from('employees')
        .select('user_id');
      
      const existingEmployeeIds = (existingEmployees || []).map((e) => e.user_id);

      const { data: existingMembers } = await supabase
        .from('members')
        .select('user_id')
        .not('user_id', 'is', null);
      
      const existingMemberIds = (existingMembers || []).map((m) => m.user_id);

      const { data: users } = await supabase
        .from('profiles')
        .select('id, email, full_name')
        .eq('is_active', true);

      return (users || []).filter((u) => 
        !existingEmployeeIds.includes(u.id) && 
        !existingMemberIds.includes(u.id)
      );
    },
    enabled: open,
  });

  const handleLinkExisting = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!linkFormData.user_id || !linkFormData.branch_id) {
      toast.error('Please select a user and branch');
      return;
    }

    setIsSubmitting(true);
    try {
      // employee_code is generated by the `employees_assign_code` trigger
      // (format EMP-<branch>-<seq>). Passing null keeps the DB authoritative.
      const { error } = await supabase.from('employees').insert({
        user_id: linkFormData.user_id,
        branch_id: linkFormData.branch_id,
        employee_code: null as any,
        department: linkFormData.department || null,
        position: linkFormData.position || null,
        hire_date: linkFormData.hire_date,
        salary: linkFormData.salary ? Number(linkFormData.salary) : null,
        salary_type: linkFormData.salary_type,
        bank_name: linkFormData.bank_name || null,
        bank_account: linkFormData.bank_account || null,
        tax_id: linkFormData.tax_id || null,
        is_active: true,
      });

      if (error) throw error;

      await supabase.from('user_roles').insert({
        user_id: linkFormData.user_id,
        role: linkFormData.role,
      });

      await supabase.from('staff_branches').insert({
        user_id: linkFormData.user_id,
        branch_id: linkFormData.branch_id,
      });

      if (linkFormData.role === 'manager') {
        await supabase.from('branch_managers').insert({
          user_id: linkFormData.user_id,
          branch_id: linkFormData.branch_id,
        });
      }

      toast.success('Employee added successfully');
      queryClient.invalidateQueries({ queryKey: ['employees'] });
      queryClient.invalidateQueries({ queryKey: ['all-staff'] });
      queryClient.invalidateQueries({ queryKey: ['available-users-for-employees'] });
      queryClient.invalidateQueries({ queryKey: ['branches'] });
      queryClient.invalidateQueries({ queryKey: ['potential-managers'] });
      queryClient.invalidateQueries({ queryKey: ['branch-manager'] });
      onOpenChange(false);
      resetForms();
    } catch (error: any) {
      console.error('Error adding employee:', error);
      toast.error(error.message || 'Failed to add employee');
    } finally {
      setIsSubmitting(false);
    }
  };

  const handleCreateNew = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!newUserFormData.email || !newUserFormData.branch_id) {
      toast.error('Please fill in email and branch');
      return;
    }

    setIsSubmitting(true);
    try {
      const { data: result, error: createError } = await supabase.functions.invoke('create-staff-user', {
        body: {
          email: newUserFormData.email,
          fullName: newUserFormData.full_name,
          phone: newUserFormData.phone,
          role: newUserFormData.role,
          branchId: newUserFormData.branch_id,
          department: newUserFormData.department || undefined,
          position: newUserFormData.position || undefined,
          salary: newUserFormData.salary ? Number(newUserFormData.salary) : undefined,
          salaryType: newUserFormData.salary_type,
          hireDate: newUserFormData.hire_date,
          bankName: newUserFormData.bank_name || undefined,
          bankAccount: newUserFormData.bank_account || undefined,
          taxId: newUserFormData.tax_id || undefined,
        },
      });

      if (createError) throw createError;
      if (result?.error) throw new Error(result.error);

      toast.success(`Employee created. Default password: ${DEFAULT_TEMP_PASSWORD}`, {
        duration: 12000,
        action: { label: 'Copy', onClick: () => navigator.clipboard.writeText(DEFAULT_TEMP_PASSWORD) },
      });
      queryClient.invalidateQueries({ queryKey: ['employees'] });
      queryClient.invalidateQueries({ queryKey: ['all-staff'] });
      queryClient.invalidateQueries({ queryKey: ['branches'] });
      queryClient.invalidateQueries({ queryKey: ['potential-managers'] });
      queryClient.invalidateQueries({ queryKey: ['branch-manager'] });
      onOpenChange(false);
      resetForms();
    } catch (error: any) {
      console.error('Error creating employee:', error);
      toast.error(error.message || 'Failed to create employee');
    } finally {
      setIsSubmitting(false);
    }
  };

  const resetForms = () => {
    setAvatarUrl('');
    setLinkFormData({
      user_id: '',
      branch_id: '',
      department: '',
      position: '',
      hire_date: new Date().toISOString().split('T')[0],
      salary: '',
      salary_type: 'monthly',
      bank_name: '',
      bank_account: '',
      tax_id: '',
      role: 'staff',
    });
    setNewUserFormData({
      email: '',
      full_name: '',
      phone: '',
      branch_id: '',
      department: '',
      position: '',
      hire_date: new Date().toISOString().split('T')[0],
      salary: '',
      salary_type: 'monthly',
      bank_name: '',
      bank_account: '',
      tax_id: '',
      role: 'staff',
    });
  };

  const renderEmploymentFields = (
    formData: any,
    setFormData: (data: any) => void
  ) => (
    <>
      <div className="grid grid-cols-2 gap-4">
        <div className="space-y-2">
          <Label>Department</Label>
          <Select
            value={formData.department || 'none'}
            onValueChange={(value) => setFormData({ ...formData, department: value === 'none' ? '' : value })}
          >
            <SelectTrigger>
              <SelectValue placeholder="Select department" />
            </SelectTrigger>
            <SelectContent>
              <SelectItem value="none">None</SelectItem>
              {DEPARTMENTS.map((dept) => (
                <SelectItem key={dept} value={dept}>{dept}</SelectItem>
              ))}
            </SelectContent>
          </Select>
        </div>
        <div className="space-y-2">
          <Label>Position</Label>
          <Select
            value={formData.position || 'none'}
            onValueChange={(value) => setFormData({ ...formData, position: value === 'none' ? '' : value })}
          >
            <SelectTrigger>
              <SelectValue placeholder="Select position" />
            </SelectTrigger>
            <SelectContent>
              <SelectItem value="none">None</SelectItem>
              {POSITIONS.map((pos) => (
                <SelectItem key={pos} value={pos}>{pos}</SelectItem>
              ))}
            </SelectContent>
          </Select>
        </div>
      </div>

      <div className="grid grid-cols-2 gap-4">
        <div className="space-y-2">
          <Label>Hire Date</Label>
          <Input
            type="date"
            value={formData.hire_date}
            onChange={(e) => setFormData({ ...formData, hire_date: e.target.value })}
          />
        </div>
        <div className="space-y-2">
          <Label>Salary Type</Label>
          <Select
            value={formData.salary_type}
            onValueChange={(value) => setFormData({ ...formData, salary_type: value })}
          >
            <SelectTrigger>
              <SelectValue />
            </SelectTrigger>
            <SelectContent>
              {SALARY_TYPES.map((t) => (
                <SelectItem key={t.value} value={t.value}>{t.label}</SelectItem>
              ))}
            </SelectContent>
          </Select>
        </div>
      </div>

      <div className="space-y-2">
        <Label>Salary (₹)</Label>
        <Input
          type="number"
          value={formData.salary}
          onChange={(e) => setFormData({ ...formData, salary: e.target.value })}
          placeholder="Salary amount"
        />
      </div>

      {/* Bank Details */}
      <div className="space-y-4 p-4 border rounded-lg">
        <h4 className="font-medium text-sm">Bank Details</h4>
        <div className="grid grid-cols-2 gap-4">
          <div className="space-y-2">
            <Label>Bank Name</Label>
            <Input
              value={formData.bank_name}
              onChange={(e) => setFormData({ ...formData, bank_name: e.target.value })}
              placeholder="e.g., HDFC Bank"
            />
          </div>
          <div className="space-y-2">
            <Label>Account Number</Label>
            <Input
              value={formData.bank_account}
              onChange={(e) => setFormData({ ...formData, bank_account: e.target.value })}
              placeholder="Account number"
            />
          </div>
        </div>
      </div>

      {/* Tax ID */}
      <div className="space-y-2">
        <Label>PAN / Tax ID</Label>
        <Input
          value={formData.tax_id}
          onChange={(e) => setFormData({ ...formData, tax_id: e.target.value })}
          placeholder="PAN number"
        />
      </div>
    </>
  );

  return (
    <Sheet open={open} onOpenChange={onOpenChange}>
      <SheetContent className="w-full sm:max-w-lg overflow-y-auto">
        <SheetHeader>
          <SheetTitle>Add Employee</SheetTitle>
          <SheetDescription>Create a new employee or link an existing user profile</SheetDescription>
        </SheetHeader>

        <Tabs value={activeTab} onValueChange={(v) => setActiveTab(v as 'new' | 'link')} className="mt-4">
          <TabsList className="grid w-full grid-cols-2">
            <TabsTrigger value="new" className="gap-2">
              <UserPlus className="h-4 w-4" />
              Create New User
            </TabsTrigger>
            <TabsTrigger value="link" className="gap-2">
              <Link className="h-4 w-4" />
              Link Existing
            </TabsTrigger>
          </TabsList>

          {/* Create New User Tab */}
          <TabsContent value="new">
            <form onSubmit={handleCreateNew} className="space-y-4 py-4">
              <div className="p-3 rounded-lg bg-info/10 border border-info/30 text-sm flex items-start gap-2">
                <Info className="h-4 w-4 text-info mt-0.5 shrink-0" />
                <div>
                  <p className="text-info font-medium">Create New User</p>
                  <p className="text-muted-foreground">The employee will receive a password setup prompt on their first login.</p>
                </div>
              </div>

              {/* Avatar Upload */}
              <div className="flex justify-center pb-2">
                <StaffAvatarUpload
                  avatarUrl={avatarUrl}
                  name={newUserFormData.full_name || 'New Employee'}
                  onAvatarChange={setAvatarUrl}
                  size="lg"
                />
              </div>

              <div className="grid grid-cols-2 gap-4">
                <div className="space-y-2">
                  <Label>Full Name *</Label>
                  <Input
                    value={newUserFormData.full_name}
                    onChange={(e) => setNewUserFormData({ ...newUserFormData, full_name: e.target.value })}
                    placeholder="John Doe"
                    required
                  />
                </div>
                <div className="space-y-2">
                  <Label>Phone</Label>
                  <PhoneInput
                    value={newUserFormData.phone}
                    onChange={(value) => setNewUserFormData({ ...newUserFormData, phone: value })}
                  />
                </div>
              </div>

              <div className="space-y-2">
                <Label>Email *</Label>
                <Input
                  type="email"
                  value={newUserFormData.email}
                  onChange={(e) => setNewUserFormData({ ...newUserFormData, email: e.target.value })}
                  placeholder="employee@gym.com"
                  required
                />
              </div>

              <div className="grid grid-cols-2 gap-4">
                <div className="space-y-2">
                  <Label>Branch *</Label>
                  <Select
                    value={newUserFormData.branch_id}
                    onValueChange={(value) => setNewUserFormData({ ...newUserFormData, branch_id: value })}
                  >
                    <SelectTrigger>
                      <SelectValue placeholder="Select branch" />
                    </SelectTrigger>
                    <SelectContent>
                      {branches.map((branch: any) => (
                        <SelectItem key={branch.id} value={branch.id}>
                          {branch.name}
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                </div>
                <div className="space-y-2">
                  <Label>Role *</Label>
                  <Select
                    value={newUserFormData.role}
                    onValueChange={(value: 'staff' | 'manager') => setNewUserFormData({ ...newUserFormData, role: value })}
                  >
                    <SelectTrigger>
                      <SelectValue />
                    </SelectTrigger>
                    <SelectContent>
                      <SelectItem value="staff">Staff</SelectItem>
                      <SelectItem value="manager">Manager</SelectItem>
                    </SelectContent>
                  </Select>
                </div>
              </div>

              {renderEmploymentFields(newUserFormData, setNewUserFormData)}

              <DefaultPasswordCard />
              <SheetFooter className="pt-4">
                <Button type="button" variant="outline" onClick={() => onOpenChange(false)}>
                  Cancel
                </Button>
                <Button type="submit" disabled={isSubmitting}>
                  {isSubmitting ? 'Creating...' : 'Create Employee'}
                </Button>
              </SheetFooter>
            </form>
          </TabsContent>

          {/* Link Existing User Tab */}
          <TabsContent value="link">
            <form onSubmit={handleLinkExisting} className="space-y-4 py-4">
              <div className="p-3 rounded-lg bg-warning/10 border border-warning/30 text-sm">
                <p className="text-warning font-medium">Link Existing Profile</p>
                <p className="text-muted-foreground">Only profiles that are NOT linked to members are shown.</p>
              </div>

              <div className="space-y-2">
                <Label>User *</Label>
                <Select
                  value={linkFormData.user_id}
                  onValueChange={(value) => setLinkFormData({ ...linkFormData, user_id: value })}
                >
                  <SelectTrigger>
                    <SelectValue placeholder="Select user" />
                  </SelectTrigger>
                  <SelectContent>
                    {availableUsers.length === 0 ? (
                      <div className="p-2 text-sm text-muted-foreground text-center">
                        No available users found
                      </div>
                    ) : (
                      availableUsers.map((user: any) => (
                        <SelectItem key={user.id} value={user.id}>
                          {user.full_name || user.email}
                        </SelectItem>
                      ))
                    )}
                  </SelectContent>
                </Select>
              </div>

              <div className="grid grid-cols-2 gap-4">
                <div className="space-y-2">
                  <Label>Branch *</Label>
                  <Select
                    value={linkFormData.branch_id}
                    onValueChange={(value) => setLinkFormData({ ...linkFormData, branch_id: value })}
                  >
                    <SelectTrigger>
                      <SelectValue placeholder="Select branch" />
                    </SelectTrigger>
                    <SelectContent>
                      {branches.map((branch: any) => (
                        <SelectItem key={branch.id} value={branch.id}>
                          {branch.name}
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                </div>
                <div className="space-y-2">
                  <Label>Role *</Label>
                  <Select
                    value={linkFormData.role}
                    onValueChange={(value: 'staff' | 'manager') => setLinkFormData({ ...linkFormData, role: value })}
                  >
                    <SelectTrigger>
                      <SelectValue />
                    </SelectTrigger>
                    <SelectContent>
                      <SelectItem value="staff">Staff</SelectItem>
                      <SelectItem value="manager">Manager</SelectItem>
                    </SelectContent>
                  </Select>
                </div>
              </div>

              {renderEmploymentFields(linkFormData, setLinkFormData)}

              <SheetFooter className="pt-4">
                <Button type="button" variant="outline" onClick={() => onOpenChange(false)}>
                  Cancel
                </Button>
                <Button type="submit" disabled={isSubmitting || availableUsers.length === 0}>
                  {isSubmitting ? 'Adding...' : 'Add Employee'}
                </Button>
              </SheetFooter>
            </form>
          </TabsContent>
        </Tabs>
      </SheetContent>
    </Sheet>
  );
}
